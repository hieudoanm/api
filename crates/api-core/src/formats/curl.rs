use crate::formats::util::{auth_for_request, base_url, collection_name, slugify};
use crate::{
    ApiAuth, ApiCollection, BodyKind, ClientFormat, ConversionFile, ConvertOptions,
    ParameterLocation, Result,
};

pub fn convert(
    collection: &ApiCollection,
    options: &ConvertOptions,
) -> Result<Vec<ConversionFile>> {
    let name = collection_name(collection, options);
    let base = effective_base(collection, options);

    let mut out = String::new();
    out.push_str("#!/usr/bin/env bash\n");
    out.push_str(&format!("# {name} — generated by api\n"));
    out.push_str("set -euo pipefail\n\n");
    out.push_str(&format!("BASE_URL={}\n\n", shell_quote(&base)));

    for folder in &collection.folders {
        out.push_str(&format!("# {}\n", folder.name));
        for request in &folder.requests {
            out.push_str(&curl_command(request, &base));
            out.push('\n');
        }
        out.push('\n');
    }

    Ok(vec![ConversionFile {
        format: ClientFormat::Curl,
        path: format!("{}.sh", slugify(&name)),
        content: out,
    }])
}

fn effective_base(collection: &ApiCollection, options: &ConvertOptions) -> String {
    if let Some(url) = options
        .base_url
        .as_deref()
        .map(str::trim)
        .filter(|s| !s.is_empty())
    {
        return url.trim_end_matches('/').to_string();
    }
    base_url(collection, options)
        .trim_end_matches('/')
        .to_string()
}

fn curl_command(request: &crate::ApiRequest, base: &str) -> String {
    let mut out = String::new();
    out.push_str(&format!("# {}\n", request.name));
    let url = request_url(base, request);
    out.push_str(&format!("curl -X {} \"{}\" \\\n", request.method, url));
    for (name, value) in headers(request) {
        out.push_str(&format!(
            "  -H {} \\\n",
            shell_quote(&format!("{name}: {value}"))
        ));
    }
    if let Some(body) = request.body.as_ref() {
        match body.kind {
            BodyKind::Json | BodyKind::Text | BodyKind::Other => {
                out.push_str(&format!(
                    "  --data {} \\\n",
                    shell_quote(&body.raw.clone().unwrap_or_default())
                ));
            }
            BodyKind::UrlEncoded => {
                let data = body
                    .fields
                    .iter()
                    .map(|f| format!("{}={}", f.name, f.value))
                    .collect::<Vec<_>>()
                    .join("&");
                out.push_str(&format!("  --data {} \\\n", shell_quote(&data)));
            }
            BodyKind::FormData => {
                for field in &body.fields {
                    if field.value == "<file>" {
                        out.push_str(&format!(
                            "  -F {}={} \\\n",
                            shell_quote(&field.name),
                            shell_quote(&format!("file=@path/to/{}", slugify(&field.name)))
                        ));
                    } else {
                        out.push_str(&format!(
                            "  -F {}={} \\\n",
                            shell_quote(&field.name),
                            shell_quote(&field.value)
                        ));
                    }
                }
            }
        }
    }
    out.push_str("  -o /dev/null -w '%{http_code}\\n'\n");
    out
}

fn request_url(_base: &str, request: &crate::ApiRequest) -> String {
    let mut path = request.path.clone();
    for param in &request.path_params {
        path = path.replace(&format!("{{{}}}", param.name), param.value.as_str());
    }
    let path = if path.starts_with('/') {
        path
    } else {
        format!("/{path}")
    };
    let mut suffix = path;
    let mut query = request
        .query_params
        .iter()
        .map(|param| format!("{}={}", param.name, param.value))
        .collect::<Vec<_>>();
    if let Some(ApiAuth::ApiKey {
        name,
        location: ParameterLocation::Query,
        value,
    }) = auth_for_request(request)
    {
        query.push(format!("{name}={value}"));
    }
    if !query.is_empty() {
        suffix.push('?');
        suffix.push_str(&query.join("&"));
    }
    format!("$BASE_URL{}", shell_escape_double(&suffix))
}

fn headers(request: &crate::ApiRequest) -> Vec<(String, String)> {
    let mut headers = request
        .headers
        .iter()
        .map(|param| (param.name.clone(), param.value.clone()))
        .collect::<Vec<_>>();
    if let Some(body) = request.body.as_ref() {
        if !headers
            .iter()
            .any(|(name, _)| name.eq_ignore_ascii_case("content-type"))
        {
            headers.push(("Content-Type".to_string(), body.content_type.clone()));
        }
    }
    match auth_for_request(request) {
        Some(ApiAuth::Bearer { token }) | Some(ApiAuth::OAuth2 { token }) => {
            headers.push(("Authorization".to_string(), format!("Bearer {token}")));
        }
        Some(ApiAuth::Basic { username, password }) => {
            headers.push((
                "Authorization".to_string(),
                format!("Basic {username}:{password}"),
            ));
        }
        Some(ApiAuth::ApiKey {
            name,
            location: ParameterLocation::Header,
            value,
        }) => {
            headers.push((name.clone(), value.clone()));
        }
        Some(ApiAuth::ApiKey {
            name,
            location: ParameterLocation::Cookie,
            value,
        }) => {
            headers.push(("Cookie".to_string(), format!("{name}={value}")));
        }
        _ => {}
    }
    headers
}

fn shell_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\\''"))
}

fn shell_escape_double(value: &str) -> String {
    let mut out = String::new();
    for ch in value.chars() {
        if matches!(ch, '"' | '\\' | '$' | '`') {
            out.push('\\');
        }
        out.push(ch);
    }
    out
}
