use std::collections::BTreeMap;

use crate::formats::util::{auth_for_request, base_url, collection_name, slugify};
use crate::{
    ApiAuth, ApiBody, ApiCollection, BodyKind, ClientFormat, ConversionFile, ConvertOptions,
    ParameterLocation, Result,
};

pub fn convert(
    collection: &ApiCollection,
    options: &ConvertOptions,
) -> Result<Vec<ConversionFile>> {
    let name = collection_name(collection, options);
    let base = effective_base(collection, options);
    let mut variables = BTreeMap::new();
    variables.insert("baseUrl".to_string(), base.clone());
    for folder in &collection.folders {
        for request in &folder.requests {
            for param in &request.path_params {
                variables.insert(param.name.clone(), placeholder_value(&param.value));
            }
            for param in &request.query_params {
                if !param.value.is_empty() {
                    variables.insert(param.name.clone(), placeholder_value(&param.value));
                }
            }
            match auth_for_request(request) {
                Some(ApiAuth::Bearer { token }) | Some(ApiAuth::OAuth2 { token }) => {
                    variables.insert("accessToken".to_string(), placeholder_value(token));
                }
                Some(ApiAuth::Basic { username, password }) => {
                    variables.insert("username".to_string(), placeholder_value(username));
                    variables.insert("password".to_string(), placeholder_value(password));
                }
                Some(ApiAuth::ApiKey {
                    name: key, value, ..
                }) => {
                    variables.insert(key.clone(), placeholder_value(value));
                }
                _ => {}
            }
        }
    }

    let mut out = String::new();
    out.push_str(&format!("# {} — generated by api\n", name));
    for (key, value) in variables {
        out.push_str(&format!("@{key} = {}\n", rest_value(&value)));
    }
    out.push('\n');

    for folder in &collection.folders {
        out.push_str(&format!("# {}\n\n", folder.name));
        for request in &folder.requests {
            out.push_str(&format!("### {} — {}\n", folder.name, request.name));
            out.push_str(&request_block(request, collection, options));
            out.push('\n');
        }
    }

    Ok(vec![ConversionFile {
        format: ClientFormat::RestClient,
        path: format!("{}.http", slugify(&name)),
        content: out,
    }])
}

fn effective_base(collection: &ApiCollection, options: &ConvertOptions) -> String {
    let raw = if let Some(url) = options
        .base_url
        .as_deref()
        .map(str::trim)
        .filter(|s| !s.is_empty())
    {
        url.to_string()
    } else {
        base_url(collection, options)
    };
    let raw = raw.trim_end_matches('/');
    if raw.starts_with("http://") || raw.starts_with("https://") || raw.is_empty() {
        raw.to_string()
    } else {
        format!(
            "https://api.example.com{}",
            if raw.starts_with('/') {
                raw.to_string()
            } else {
                format!("/{raw}")
            }
        )
    }
}

fn request_block(
    request: &crate::ApiRequest,
    collection: &ApiCollection,
    options: &ConvertOptions,
) -> String {
    let _ = collection;
    let _ = options;
    let server = effective_base(collection, options);
    let url = request_url(&server, request);
    let mut out = String::new();
    out.push_str(&format!("{} {}\n", request.method, url));
    for header in headers(request) {
        out.push_str(&format!("{}: {}\n", header.0, header.1));
    }
    if let Some(body) = request.body.as_ref() {
        out.push('\n');
        out.push_str(&body_text(body));
        out.push('\n');
    }
    out
}

fn request_url(server: &str, request: &crate::ApiRequest) -> String {
    let mut path = request.path.clone();
    for param in &request.path_params {
        path = path.replace(
            &format!("{{{}}}", param.name),
            &format!("{{{{{}}}}}", param.name),
        );
    }
    let path = if path.starts_with('/') {
        path
    } else {
        format!("/{path}")
    };
    let mut url = format!("{{{{baseUrl}}}}{path}");
    let _ = server;
    let mut query = Vec::new();
    for param in &request.query_params {
        query.push(format!("{}={}", param.name, param.value));
    }
    if let Some(ApiAuth::ApiKey {
        name,
        location: ParameterLocation::Query,
        value,
    }) = auth_for_request(request)
    {
        query.push(format!("{name}={value}"));
    }
    if !query.is_empty() {
        url.push('?');
        url.push_str(&query.join("&"));
    }
    url
}

fn headers(request: &crate::ApiRequest) -> Vec<(String, String)> {
    let mut headers = request
        .headers
        .iter()
        .map(|param| (param.name.clone(), param.value.clone()))
        .collect::<Vec<_>>();
    if let Some(body) = request.body.as_ref() {
        if !headers
            .iter()
            .any(|(name, _)| name.eq_ignore_ascii_case("content-type"))
        {
            headers.push(("Content-Type".to_string(), body.content_type.clone()));
        }
    }
    match auth_for_request(request) {
        Some(ApiAuth::Bearer { token }) | Some(ApiAuth::OAuth2 { token }) => {
            headers.push(("Authorization".to_string(), format!("Bearer {token}")));
        }
        Some(ApiAuth::Basic { username, password }) => {
            headers.push((
                "Authorization".to_string(),
                format!("Basic {username}:{password}"),
            ));
        }
        Some(ApiAuth::ApiKey {
            name,
            location: ParameterLocation::Header,
            value,
        }) => {
            headers.push((name.clone(), value.clone()));
        }
        Some(ApiAuth::ApiKey {
            name,
            location: ParameterLocation::Cookie,
            value,
        }) => {
            headers.push(("Cookie".to_string(), format!("{name}={value}")));
        }
        _ => {}
    }
    headers
}

fn body_text(body: &ApiBody) -> String {
    match body.kind {
        BodyKind::Json | BodyKind::Text | BodyKind::Other => body.raw.clone().unwrap_or_default(),
        BodyKind::UrlEncoded => body
            .fields
            .iter()
            .map(|field| format!("{}={}", field.name, field.value))
            .collect::<Vec<_>>()
            .join("&"),
        BodyKind::FormData => body
            .fields
            .iter()
            .map(|field| {
                if field.value == "<file>" {
                    format!("{}=@file(path/to/{})", field.name, slugify(&field.name))
                } else {
                    format!("{}={}", field.name, field.value)
                }
            })
            .collect::<Vec<_>>()
            .join("\n"),
    }
}

fn placeholder_value(value: &str) -> String {
    value
        .strip_prefix("{{")
        .and_then(|v| v.strip_suffix("}}"))
        .unwrap_or(value)
        .to_string()
}

fn rest_value(value: &str) -> String {
    if value.contains(' ') || value.contains('#') {
        format!("\"{}\"", value.replace('"', "\\\""))
    } else {
        value.to_string()
    }
}
